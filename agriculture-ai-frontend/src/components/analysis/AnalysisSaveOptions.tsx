import { useQuery } from "@tanstack/react-query";

import { useAuth } from "@/lib/auth-context";
import { listOwnedFarmFields, startGoogleSignIn } from "@/lib/api";

export function AnalysisSaveOptions({
  saveToHistory,
  onSaveToHistoryChange,
  fieldId,
  onFieldIdChange,
}: {
  saveToHistory: boolean;
  onSaveToHistoryChange: (value: boolean) => void;
  fieldId: string;
  onFieldIdChange: (value: string) => void;
}) {
  const auth = useAuth();
  const fieldsQuery = useQuery({
    queryKey: ["analysis-save-fields"],
    queryFn: listOwnedFarmFields,
    enabled: saveToHistory && auth.status === "authenticated",
  });

  return (
    <section className="rounded-2xl border border-border bg-card/80 p-4">
      <label className="flex items-start gap-3 text-sm font-semibold text-foreground">
        <input
          type="checkbox"
          className="mt-1 size-4 accent-emerald-700"
          checked={saveToHistory}
          disabled={auth.status !== "authenticated"}
          onChange={(event) => onSaveToHistoryChange(event.target.checked)}
        />
        <span>
          Save this result to Analysis History
          <span className="mt-1 block text-xs font-normal text-foreground/60">
            Only the result generated by the server is saved.
          </span>
        </span>
      </label>
      {auth.status === "unauthenticated" && (
        <button
          type="button"
          className="mt-3 text-sm font-semibold text-primary underline"
          onClick={startGoogleSignIn}
        >
          Sign in to save analyses
        </button>
      )}
      {auth.status === "error" && (
        <p className="mt-3 text-sm text-destructive" role="alert">
          {auth.error} Retry the session check before saving.
        </p>
      )}
      {saveToHistory && auth.status === "authenticated" && (
        <label className="mt-4 block text-sm font-medium text-foreground">
          Associate with a field <span className="font-normal opacity-60">(optional)</span>
          <select
            className="mt-1 w-full rounded-xl border border-border bg-background px-3 py-2 text-sm"
            value={fieldId}
            onChange={(event) => onFieldIdChange(event.target.value)}
            disabled={fieldsQuery.isPending || fieldsQuery.isError}
          >
            <option value="">No field association</option>
            {fieldsQuery.data?.map((field) => (
              <option key={field.id} value={field.id}>
                {field.farm_name} — {field.name}
              </option>
            ))}
          </select>
          {fieldsQuery.isPending && (
            <span className="mt-1 block text-xs text-foreground/60">Loading your fields…</span>
          )}
          {fieldsQuery.isError && (
            <span className="mt-1 block text-xs text-destructive" role="alert">
              Field selection is unavailable. You can save without associating a field.
            </span>
          )}
        </label>
      )}
    </section>
  );
}
